import type { LocalText } from './types'

export type Availability = 'deployment' | 'assessment' | 'scope'
export type Metric = {
  name: LocalText
  definition: LocalText
  unit: LocalText
  decision: LocalText
  prerequisite: LocalText
  limitation: LocalText
  status: Availability
}

const l = (en: string, id: string): LocalText => ({ en, id })
const metric = (
  name: string,
  definitionEn: string,
  definitionId: string,
  unitEn: string,
  unitId: string,
  decisionEn: string,
  decisionId: string,
  prerequisiteEn: string,
  prerequisiteId: string,
  limitationEn: string,
  limitationId: string,
  status: Availability,
): Metric => ({
  name: l(name, name),
  definition: l(definitionEn, definitionId),
  unit: l(unitEn, unitId),
  decision: l(decisionEn, decisionId),
  prerequisite: l(prerequisiteEn, prerequisiteId),
  limitation: l(limitationEn, limitationId),
  status,
})

